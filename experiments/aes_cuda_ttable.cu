__device__ __forceinline__ unsigned int load_be(const unsigned char* p) {
    return ((unsigned int)p[0]<<24)|((unsigned int)p[1]<<16)|((unsigned int)p[2]<<8)|p[3];
}
__device__ __forceinline__ unsigned int ror(unsigned int x, int n) {
    return (x>>n)|(x<<(32-n));
}
__device__ __forceinline__ unsigned int final_word(unsigned int a, unsigned int b,
                                                  unsigned int c, unsigned int d) {
    return ((unsigned int)sbox[a>>24]<<24)|((unsigned int)sbox[(b>>16)&255]<<16)|
           ((unsigned int)sbox[(c>>8)&255]<<8)|sbox[d&255];
}
__device__ __forceinline__ void encrypt_table(unsigned char* bytes, const unsigned char* rk) {
    unsigned int a=load_be(bytes)^load_be(rk);
    unsigned int b=load_be(bytes+4)^load_be(rk+4);
    unsigned int c=load_be(bytes+8)^load_be(rk+8);
    unsigned int d=load_be(bytes+12)^load_be(rk+12);
    #pragma unroll 9
    for(int round=1;round<10;++round) {
        unsigned int x=te0[a>>24]^ror(te0[(b>>16)&255],8)^ror(te0[(c>>8)&255],16)^ror(te0[d&255],24)^load_be(rk+16*round);
        unsigned int y=te0[b>>24]^ror(te0[(c>>16)&255],8)^ror(te0[(d>>8)&255],16)^ror(te0[a&255],24)^load_be(rk+16*round+4);
        unsigned int z=te0[c>>24]^ror(te0[(d>>16)&255],8)^ror(te0[(a>>8)&255],16)^ror(te0[b&255],24)^load_be(rk+16*round+8);
        unsigned int w=te0[d>>24]^ror(te0[(a>>16)&255],8)^ror(te0[(b>>8)&255],16)^ror(te0[c&255],24)^load_be(rk+16*round+12);
        a=x; b=y; c=z; d=w;
    }
    // Last round deliberately omits MixColumns.
    unsigned int result[4]={final_word(a,b,c,d)^load_be(rk+160),
                           final_word(b,c,d,a)^load_be(rk+164),
                           final_word(c,d,a,b)^load_be(rk+168),
                           final_word(d,a,b,c)^load_be(rk+172)};
    #pragma unroll 4
    for(int j=0;j<4;++j) {
        bytes[4*j]=result[j]>>24; bytes[4*j+1]=result[j]>>16;
        bytes[4*j+2]=result[j]>>8; bytes[4*j+3]=result[j];
    }
}
extern "C" __global__ void aes_ecb_ttable(const unsigned char* in, unsigned char* out,
    const unsigned char* rk, unsigned long long n) {
    unsigned long long offset=16*((unsigned long long)blockIdx.x*blockDim.x+threadIdx.x);
    if(offset>=n) return;
    unsigned char s[16];
    for(int j=0;j<16;++j) s[j]=in[offset+j];
    encrypt_table(s,rk);
    for(int j=0;j<16;++j) out[offset+j]=s[j];
}
extern "C" __global__ void aes_ctr_ttable(const unsigned char* in, unsigned char* out,
    const unsigned char* rk, const unsigned char* initial, unsigned long long n) {
    unsigned long long index=(unsigned long long)blockIdx.x*blockDim.x+threadIdx.x;
    unsigned long long offset=16*index;
    if(offset>=n) return;
    unsigned char s[16];
    unsigned long long carry=index;
    for(int j=15;j>=0;--j) { carry+=initial[j]; s[j]=(unsigned char)carry; carry>>=8; }
    encrypt_table(s,rk);
    for(int j=0;j<16 && offset+j<n;++j) out[offset+j]=in[offset+j]^s[j];
}
