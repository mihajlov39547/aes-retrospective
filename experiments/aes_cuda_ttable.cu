__device__ unsigned char xtime(unsigned char x) {
    return (unsigned char)((x << 1) ^ ((x & 128) ? 0x1b : 0));
}

extern "C" __global__ void expand_key(const unsigned char* key, unsigned char* rk) {
    // Exactly one thread, outside every timed region.
    for (int i=0; i<16; ++i) rk[i]=key[i];
    unsigned char rcon=1;
    for (int n=16; n<176; n+=4) {
        unsigned char t[4];
        for(int i=0;i<4;++i) t[i]=rk[n-4+i];
        if(n%16==0) {
            unsigned char first=t[0];
            t[0]=sbox[t[1]]^rcon; t[1]=sbox[t[2]];
            t[2]=sbox[t[3]]; t[3]=sbox[first]; rcon=xtime(rcon);
        }
        for(int i=0;i<4;++i) rk[n+i]=rk[n-16+i]^t[i];
    }
}


